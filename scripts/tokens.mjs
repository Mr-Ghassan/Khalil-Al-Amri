/**
 * Derives web tokens from the approved KHA Design System v1.1 token files.
 * Sources (copied verbatim from Drive, never edited by hand):
 *   src/tokens/design-tokens.resolved.source.json  (15_Design_System/02_Tokens)
 *   src/tokens/motion-tokens.source.css            (16_Motion_System/02_Motion_Tokens)
 * Output: src/styles/tokens.generated.css — brand values keep their source names;
 * web-only roles are prefixed --web-* and documented as DERIVED.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../src/tokens/design-tokens.resolved.source.json', import.meta.url), 'utf8'));
const motionCss = readFileSync(new URL('../src/tokens/motion-tokens.source.css', import.meta.url), 'utf8');

const lines = [];
// The resolved file is flat: { "color.palette.ink": "#17222B", ... }
const group = (prefix) => Object.fromEntries(Object.entries(src).filter(([k]) => k.startsWith(prefix + '.')).map(([k, v]) => [k.slice(prefix.length + 1), v]));
const one = (key) => { if (!(key in src)) throw new Error(`missing token ${key}`); return src[key]; };
const push = (name, value) => lines.push(`  --kha-${name}: ${value};`);

for (const [k, v] of Object.entries(group('color.palette'))) push(`color-${k}`, v);
for (const [k, v] of Object.entries(group('color.ambient'))) push(`ambient-${k}`, v);
for (const [k, v] of Object.entries(group('color.text'))) push(`text-${k}`, v);
for (const [k, v] of Object.entries(group('color.border'))) push(`border-${k}`, v);
for (const [k, v] of Object.entries(group('color.signature'))) push(`signature-${k}`, v);
for (const [k, v] of Object.entries(group('spacing.scale'))) push(`space-${k}`, `${v}px`);
for (const [k, v] of Object.entries(group('radius'))) push(`radius-${k}`, typeof v === 'number' ? `${v}px` : String(v));
push('shadow-lift', one('shadow.lift'));
push('shadow-paper', one('shadow.paper'));
push('grain-subtle', one('texture.grain.subtle'));
push('grain-hero', one('texture.grain.hero'));
push('display-line-height-min', one('typography.display-line-height-min'));
push('caps-tracking', one('typography.caps-tracking'));

// Motion: keep only time/easing tokens usable on the web.
const motion = [...motionCss.matchAll(/--kha-motion-(duration|delay|ease)-([a-z]+):\s*([^;]+);/g)]
  .map(([, g, k, v]) => `  --kha-motion-${g}-${k}: ${v.trim()};`);

const out = `/* GENERATED by scripts/tokens.mjs from the approved KHA Design System v1.1 + Motion System v1.1 tokens.
   Do not edit by hand. Source version: v1.1.0 (resolved) */
:root {
${lines.join('\n')}
${motion.join('\n')}
}
`;
writeFileSync(new URL('../src/styles/tokens.generated.css', import.meta.url), out);
console.log(`tokens: ${lines.length + motion.length} custom properties → src/styles/tokens.generated.css`);
